/* Collect the license of every RUNTIME npm package the app ships, write each
 * one's license text into licenses/npm/ (shipped via extraResources so the
 * in-app Finder folder is complete), and regenerate the corresponding section
 * of THIRD-PARTY-NOTICES.md between its generated markers.
 *
 * Runtime only: devDependencies are build tooling and are not redistributed.
 * The tree is walked with require.resolve from each package's own directory,
 * which is what Node — and therefore the packaged asar — actually resolves.
 * Reading the flat top-level node_modules instead would report the wrong
 * versions, because dev tooling hoists different copies of the same names.
 *
 * Run after any dependency change:  node scripts/collect-runtime-licenses.js
 */
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const OUT_DIR = path.join(ROOT, 'licenses', 'npm');
const NOTICES = path.join(ROOT, 'THIRD-PARTY-NOTICES.md');
const BEGIN = '<!-- BEGIN npm-runtime (generated by scripts/collect-runtime-licenses.js) -->';
const END = '<!-- END npm-runtime -->';
const LICENSE_NAMES = /^(LICENSE|LICENCE|COPYING)(\.(md|txt))?$/i;

function readPkg(dir) {
  return JSON.parse(fs.readFileSync(path.join(dir, 'package.json'), 'utf8'));
}

function resolveDep(name, fromDir) {
  try {
    return path.dirname(require.resolve(path.join(name, 'package.json'), { paths: [fromDir] }));
  } catch {
    /* Packages with an "exports" map may hide package.json. Walk up the
       node_modules chain by hand. */
    let dir = fromDir;
    for (;;) {
      const c = path.join(dir, 'node_modules', name);
      if (fs.existsSync(path.join(c, 'package.json'))) return c;
      const up = path.dirname(dir);
      if (up === dir) return null;
      dir = up;
    }
  }
}

const found = new Map();
(function walk(dir) {
  const pkg = readPkg(dir);
  for (const name of Object.keys(pkg.dependencies || {})) {
    const depDir = resolveDep(name, dir);
    if (!depDir) { console.error(`  !! could not resolve ${name} from ${dir}`); continue; }
    const dep = readPkg(depDir);
    const key = `${dep.name}@${dep.version}`;
    if (found.has(key)) continue;
    found.set(key, { dir: depDir, pkg: dep });
    walk(depDir);
  }
})(ROOT);

const holderOf = (p) => {
  const a = p.author;
  if (a) return typeof a === 'string' ? a : [a.name, a.email && `<${a.email}>`].filter(Boolean).join(' ');
  if (Array.isArray(p.contributors) && p.contributors.length) {
    const c = p.contributors[0];
    return typeof c === 'string' ? c : c.name;
  }
  return null;
};
const stripUrl = (s) => (s || '').replace(/\s*\(https?:\/\/[^)]*\)/g, '').trim();

const entries = [...found.values()]
  .map(({ dir, pkg }) => {
    const license = typeof pkg.license === 'object' ? pkg.license.type : pkg.license;
    const file = fs.readdirSync(dir).find((f) => LICENSE_NAMES.test(f)) || null;
    return {
      name: pkg.name,
      version: pkg.version,
      license: license || 'UNKNOWN',
      holder: stripUrl(holderOf(pkg)),
      homepage: pkg.homepage || (pkg.repository && (pkg.repository.url || pkg.repository)) || null,
      text: file ? fs.readFileSync(path.join(dir, file), 'utf8') : null,
      file,
    };
  })
  .sort((a, b) => a.name.localeCompare(b.name));

/* ── license texts ──────────────────────────────────────────────────────── */
fs.rmSync(OUT_DIR, { recursive: true, force: true });
fs.mkdirSync(OUT_DIR, { recursive: true });
let missing = 0;
for (const e of entries) {
  const dest = path.join(OUT_DIR, `${e.name}.txt`);
  if (e.text) {
    fs.writeFileSync(dest, e.text.endsWith('\n') ? e.text : e.text + '\n');
  } else {
    /* Do NOT invent a license text. Record exactly what upstream declares. */
    missing++;
    fs.writeFileSync(dest,
      `${e.name} ${e.version}\n\n` +
      `Declared license: ${e.license} (package.json "license" field).\n` +
      (e.holder ? `Author: ${e.holder}\n` : '') +
      (e.homepage ? `Upstream: ${e.homepage}\n` : '') +
      `\nThis package ships no LICENSE file of its own; the line above is the\n` +
      `license it declares. No license text has been substituted here, because\n` +
      `inventing one would misstate the copyright holder's terms.\n`);
  }
}

/* ── notices section ────────────────────────────────────────────────────── */
const licenseCounts = entries.reduce((m, e) => (m[e.license] = (m[e.license] || 0) + 1, m), {});
const summary = Object.entries(licenseCounts).sort((a, b) => b[1] - a[1])
  .map(([l, n]) => `${l} (${n})`).join(', ');

const md = [
  BEGIN,
  '',
  `SkinnyVideo bundles ${entries.length} npm packages at runtime — \`electron-updater\` and its`,
  'transitive dependencies, which provide the automatic-update check. Everything',
  'else in `node_modules` is build tooling and is not redistributed.',
  '',
  `Licenses in this set: ${summary}. Each package's own license text ships in the`,
  'app as `licenses/npm/<package>.txt`.',
  '',
  '| Package | Version | License | Copyright holder |',
  '| --- | --- | --- | --- |',
  ...entries.map((e) => `| \`${e.name}\` | ${e.version} | ${e.license} | ${e.holder || 'see bundled license text'} |`),
  '',
  END,
].join('\n');

let notices = fs.readFileSync(NOTICES, 'utf8');
if (notices.includes(BEGIN) && notices.includes(END)) {
  notices = notices.replace(new RegExp(`${BEGIN.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}[\\s\\S]*?${END.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}`), md);
} else {
  const heading = '## Bundled npm packages\n\n';
  const anchor = '## Fonts — SIL Open Font License 1.1';
  notices = notices.includes(anchor)
    ? notices.replace(anchor, heading + md + '\n\n' + anchor)
    : notices.trimEnd() + '\n\n' + heading + md + '\n';
}
fs.writeFileSync(NOTICES, notices);

console.log(`runtime packages: ${entries.length}`);
console.log(`licenses: ${summary}`);
console.log(`license texts written to licenses/npm/ (${entries.length} files, ${missing} without upstream text)`);
for (const e of entries) console.log(`  ${e.name.padEnd(22)} ${e.version.padEnd(9)} ${e.license.padEnd(15)} ${e.file || '(no LICENSE file upstream)'}`);
